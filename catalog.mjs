const slug = name => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const weightMode = equipment => equipment === 'Dumbbell' ? 'per-dumbbell'
  : ['Machine', 'Cable'].includes(equipment) ? 'machine-total'
    : equipment === 'Bodyweight' ? 'bodyweight' : 'total';

export const CATALOG = Object.entries(groups).flatMap(([group, entries]) => entries.map(([name, equipment, convention]) => ({
  id: `builtin-${slug(name)}`,
  name,
  equipment,
  group,
  // Assistance is entered as the machine's positive displayed help, never as a
  // negative resistance or combined with an unassisted exercise's history.
  weightMode: convention ?? weightMode(equipment),
})));

